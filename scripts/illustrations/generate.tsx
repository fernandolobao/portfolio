/**
 * Renders the SVG illustrations to static markup so the site can inject them
 * with dangerouslySetInnerHTML. React then skips hydrating those nodes, which
 * keeps the main thread free on slow devices.
 *
 * Run: npm run build:illustrations  (output: components/illustrations/generated.ts)
 */
import { writeFileSync } from "node:fs";
import path from "node:path";

import { renderToStaticMarkup } from "react-dom/server";

import { HeroIllustration } from "./hero-illustration";
import { ProjectIllustration, illustrationIds } from "./project-illustrations";

const out: Record<string, string> = {
  hero: renderToStaticMarkup(<HeroIllustration />),
};
for (const id of illustrationIds) {
  out[id] = renderToStaticMarkup(<ProjectIllustration id={id} />);
}

const file = `// AUTO-GENERATED by scripts/illustrations/generate.tsx. Do not edit by hand.
export const illustrations: Record<string, string> = ${JSON.stringify(out, null, 2)};
`;

writeFileSync(
  path.join(process.cwd(), "components/illustrations/generated.ts"),
  file
);
console.log("illustrations generated:", Object.keys(out).join(", "));
